import * as React from "react"

import { generateTheme } from "@/theme/generate"
import { parseBrandColor, type ParseResult } from "@/theme/parse"
import { serializeGlobalsCss } from "@/theme/serialize"
import { formatOklch } from "@/theme/color"
import { DEFAULT_OPTIONS, type GeneratedTheme, type Oklch, type ThemeOptions } from "@/theme/types"

import { DEFAULT_STATE, loadInitialState, saveState, type PreviewMode } from "./persistence"

interface ThemeLabValue {
  brandInput: string
  setBrandInput: (value: string) => void
  parsed: ParseResult
  /** Last successfully parsed brand; the preview keeps it while input is invalid. */
  brand: Oklch
  options: ThemeOptions
  setOption: <K extends keyof ThemeOptions>(key: K, value: ThemeOptions[K]) => void
  resetOptions: () => void
  previewMode: PreviewMode
  setPreviewMode: (mode: PreviewMode) => void
  theme: GeneratedTheme
  css: string
  includeFont: boolean
  setIncludeFont: (value: boolean) => void
}

const ThemeLabContext = React.createContext<ThemeLabValue | null>(null)

export function ThemeLabProvider({ children }: { children: React.ReactNode }) {
  const [initial] = React.useState(loadInitialState)
  const [brandInput, setBrandInput] = React.useState(initial.brand)
  const [options, setOptions] = React.useState<ThemeOptions>(initial.options)
  const [previewMode, setPreviewMode] = React.useState<PreviewMode>(initial.previewMode)
  const [includeFont, setIncludeFont] = React.useState(true)

  const parsed = React.useMemo(() => parseBrandColor(brandInput), [brandInput])
  const [lastValid, setLastValid] = React.useState<Oklch>(() => {
    if (parsed.ok) return parsed.color
    const r = parseBrandColor(DEFAULT_STATE.brand)
    return r.ok ? r.color : { l: 0.42, c: 0.1, h: 155 }
  })
  // Adjust state during render (React's recommended pattern) to remember the last valid brand.
  if (parsed.ok && parsed.color !== lastValid) setLastValid(parsed.color)
  const brand = parsed.ok ? parsed.color : lastValid

  // One generation per (brand, options) change; the preview only consumes CSS variables.
  const theme = React.useMemo(() => generateTheme(brand, options), [brand, options])
  const css = React.useMemo(
    () =>
      serializeGlobalsCss(theme, {
        includeFont,
        header: [
          "Generated by shadcn colors",
          `Brand ${formatOklch(theme.analysis.brand)}`,
          `Options tint=${options.surfaceTint} accent=${options.accentStrength} border=${options.borderStrength} contrast=${options.contrast} darkPrimary=${options.darkPrimaryLightness ?? "auto"}`,
        ],
      }),
    [theme, options, includeFont]
  )

  // Persist only valid states, debounced so typing stays smooth.
  React.useEffect(() => {
    if (!parsed.ok) return
    const id = window.setTimeout(() => saveState({ brand: brandInput, options, previewMode }), 200)
    return () => window.clearTimeout(id)
  }, [brandInput, options, previewMode, parsed.ok])

  const setOption = React.useCallback(<K extends keyof ThemeOptions>(key: K, value: ThemeOptions[K]) => {
    setOptions((prev) => ({ ...prev, [key]: value }))
  }, [])
  const resetOptions = React.useCallback(() => setOptions(DEFAULT_OPTIONS), [])

  const value = React.useMemo<ThemeLabValue>(
    () => ({
      brandInput,
      setBrandInput,
      parsed,
      brand,
      options,
      setOption,
      resetOptions,
      previewMode,
      setPreviewMode,
      theme,
      css,
      includeFont,
      setIncludeFont,
    }),
    [brandInput, parsed, brand, options, setOption, resetOptions, previewMode, theme, css, includeFont]
  )

  return <ThemeLabContext.Provider value={value}>{children}</ThemeLabContext.Provider>
}

export function useThemeLab() {
  const ctx = React.useContext(ThemeLabContext)
  if (!ctx) throw new Error("useThemeLab must be used within ThemeLabProvider")
  return ctx
}
